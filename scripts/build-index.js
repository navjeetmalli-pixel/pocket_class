#!/usr/bin/env node
// Writes data/class{N}/index.js for every class: the small file the app loads at start-up.
// Per subject it holds the syllabus and, for each chapter, id, title, section, summary and the number of
// flashcard terms. No notes or questions, so a class opens fast; a subject's full file loads when it is needed.
// Run it after changing any subject file (npm run sync does). scripts/validate.js fails if an index is stale.
//
//   node scripts/build-index.js            rewrite the index files
//   node scripts/build-index.js --check    only report which are out of date (exit 1 if any)

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const dataDir = path.join(root, "data");

const classDirs = () => fs.readdirSync(dataDir).filter((d) => /^class\d+$/.test(d)).sort((a, b) => Number(a.slice(5)) - Number(b.slice(5)));
const subjectFiles = (dir) => fs.readdirSync(path.join(dataDir, dir)).filter((f) => f.endsWith(".js") && f !== "index.js" && f !== "objectives.js").sort();

// The text index.js should contain for one class directory.
function indexFor(dir) {
  const cls = Number(dir.slice(5));
  const index = {};
  for (const f of subjectFiles(dir)) {
    const ctx = { globalThis: {} };
    ctx.globalThis = ctx;
    vm.createContext(ctx);
    vm.runInContext(fs.readFileSync(path.join(root, "data", "registry.js"), "utf8"), ctx);
    vm.runInContext(fs.readFileSync(path.join(dataDir, dir, f), "utf8"), ctx, { filename: f });
    const data = ctx.StudyData.content[cls] && ctx.StudyData.content[cls][path.basename(f, ".js")];
    if (!data) throw new Error(`${dir}/${f} does not add content for class ${cls}`);
    index[path.basename(f, ".js")] = {
      syllabus: data.syllabus,
      chapters: data.chapters.map((c) => ({ id: c.id, title: c.title, section: c.section, summary: c.summary, nTerms: (c.terms || []).length })),
    };
  }
  return (
    `// GENERATED by scripts/build-index.js from the subject files in this folder. Do not edit; run: node scripts/build-index.js\n` +
    `StudyData.addIndex(${cls}, ${JSON.stringify(index)});\n`
  );
}

// [{ file, ok }] for every class.
function check() {
  return classDirs().map((dir) => {
    const file = path.join("data", dir, "index.js");
    const full = path.join(root, file);
    return { file, ok: fs.existsSync(full) && fs.readFileSync(full, "utf8") === indexFor(dir) };
  });
}

function build() {
  for (const dir of classDirs()) {
    const text = indexFor(dir);
    fs.writeFileSync(path.join(dataDir, dir, "index.js"), text);
    console.log(`data/${dir}/index.js  ${(Buffer.byteLength(text) / 1024).toFixed(0)} KB`);
  }
}

module.exports = { check, build };

if (require.main === module) {
  if (process.argv.includes("--check")) {
    const stale = check().filter((r) => !r.ok);
    stale.forEach((r) => console.log(`stale: ${r.file}`));
    process.exit(stale.length ? 1 : 0);
  } else build();
}
