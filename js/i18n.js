// Interface language: English (default), ਪੰਜਾਬੀ (pa) or हिंदी (hi).
// Only the app's own menus, buttons, messages and printed headings change. Study content is never translated.
//
// Every visible string in the code is written in English inside t("..."). t() looks that exact English text up in
// the table of the chosen language and falls back to the English text, so a missing translation just shows English.
//   t("Mock test")                              -> "ਮੌਕ ਟੈਸਟ" in Punjabi
//   t("{n} chapters done", { n: 3 })            -> {name} placeholders are filled in
//   t("{n} {n:chapter|chapters}", { n: 1 })     -> {n:one|many} picks a word by the number (English only; the
//                                                  Punjabi and Hindi lines just use {n}, as their words don't change)
// The chosen language is saved as Store.state.lang ("en" | "pa" | "hi").

const LANGS = [
  ["en", "English"],
  ["pa", "ਪੰਜਾਬੀ"],
  ["hi", "हिंदी"],
];
const LOCALES = { en: "en-IN", pa: "pa-IN", hi: "hi-IN" };

function currentLang() {
  const l = typeof Store !== "undefined" && Store.state.lang;
  return l === "pa" || l === "hi" ? l : "en";
}

// Locale for dates (weekday names and so on).
const langTag = () => LOCALES[currentLang()];

// Weekday and month names. Browsers often lack Punjabi date data and show English, so they are listed here.
const DAYS = {
  pa: ["ਐਤ", "ਸੋਮ", "ਮੰਗਲ", "ਬੁੱਧ", "ਵੀਰ", "ਸ਼ੁੱਕਰ", "ਸ਼ਨਿੱਚਰ"],
  hi: ["रवि", "सोम", "मंगल", "बुध", "गुरु", "शुक्र", "शनि"],
};
const MONTHS = {
  pa: ["ਜਨ", "ਫ਼ਰ", "ਮਾਰਚ", "ਅਪ੍ਰੈ", "ਮਈ", "ਜੂਨ", "ਜੁਲਾ", "ਅਗ", "ਸਤੰ", "ਅਕ", "ਨਵੰ", "ਦਸੰ"],
  hi: ["जन॰", "फ़र॰", "मार्च", "अप्रैल", "मई", "जून", "जुला॰", "अग॰", "सित॰", "अक्तू॰", "नव॰", "दिस॰"],
};

// "Mon" / "Tue"… in the chosen language.
function weekdayShort(d) {
  const l = currentLang();
  return DAYS[l] ? DAYS[l][d.getDay()] : d.toLocaleDateString(langTag(), { weekday: "short" });
}

// "5 Nov" in the chosen language.
function dateShort(d) {
  const l = currentLang();
  return MONTHS[l] ? `${d.getDate()} ${MONTHS[l][d.getMonth()]}` : d.toLocaleDateString(langTag(), { day: "numeric", month: "short" });
}

function t(english, vars) {
  const table = I18N[currentLang()];
  const text = (table && table[english]) || english;
  if (!vars) return text;
  return text.replace(/\{(\w+)(?::([^|}]*)\|([^}]*))?\}/g, (whole, name, one, many) => {
    if (!(name in vars)) return whole;
    if (one === undefined) return vars[name];
    return Number(vars[name]) === 1 ? one : many;
  });
}

// Sets the page language and the parts of index.html that are plain text. Call after the language changes.
function applyLang() {
  document.documentElement.lang = currentLang();
  const skip = document.getElementById("skip");
  if (skip) skip.textContent = t("Skip to content");
  document.querySelectorAll("nav[aria-label]").forEach((n) => n.setAttribute("aria-label", t("Main")));
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.content = t("Notes, flashcards, quizzes and mock tests for CBSE / NCERT and PSEB Classes 1 to 12, in every main subject. Works offline.");
}

